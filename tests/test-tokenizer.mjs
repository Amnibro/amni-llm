import {loadGGUF} from '../backends/wgpu/gguf.js';
import {Tokenizer} from '../backends/wgpu/tokenizer.js';
const URL='https://huggingface.co/Qwen/Qwen2.5-0.5B-Instruct-GGUF/resolve/main/qwen2.5-0.5b-instruct-q4_k_m.gguf';
let pass=0,fail=0;
const check=(cond,msg)=>{cond?(console.log('  PASS  '+msg),pass++):(console.log('  FAIL  '+msg),fail++);};
const log=(...a)=>console.log(...a);
log('Loading GGUF '+URL);
const g=await loadGGUF(URL);
log('GGUF loaded: arch='+g.arch+', '+g.tensors.size+' tensors, '+g.metadata.size+' KV');
const tok=await Tokenizer.fromGGUF(g);
log('\nTokenizer:');
log('  vocab size: '+tok.vocab.length);
log('  merges: '+tok.merges.length);
log('  bos: '+tok.bosId+' ('+(tok.bosId!==undefined?tok.vocab[tok.bosId]:'?')+')');
log('  eos: '+tok.eosId+' ('+(tok.eosId!==undefined?tok.vocab[tok.eosId]:'?')+')');
log('  pad: '+tok.padId+' ('+(tok.padId!==undefined?tok.vocab[tok.padId]:'?')+')');
log('  im_start: '+tok.imStartId);
log('  im_end: '+tok.imEndId);
log('\nRound-trip tests:');
const cases=['Hello, world!','The quick brown fox jumps over the lazy dog.','Πίνω ζεστή σοκολάτα.','日本語のテスト','def add(a, b): return a + b','1 + 2 = 3','   leading spaces','trailing spaces   ','newline\ntest','tab\ttest'];
for(const text of cases){const ids=tok.encode(text,{addBos:false});const back=tok.decode(ids);check(back===text,'round-trip "'+text.replace(/\n/g,'\\n').replace(/\t/g,'\\t')+'" → '+ids.length+' tokens → "'+back.replace(/\n/g,'\\n').replace(/\t/g,'\\t')+'"');}
log('\nChat template:');
const chat=[{role:'system',content:'You are a helpful AI.'},{role:'user',content:'What is 2+2?'}];
const formatted=tok.formatChat(chat);
log('  formatted preview:');
log('  '+formatted.replace(/\n/g,'\\n'));
const chatIds=tok.encodeChat(chat);
log('  encoded chat: '+chatIds.length+' tokens');
log('  first 8 ids: '+chatIds.slice(0,8).join(', '));
check(chatIds.length>0,'chat encoding produces tokens');
check(chatIds.includes(tok.imStartId),'chat encoding contains <|im_start|>');
log('\n=== '+pass+' pass, '+fail+' fail ===');
process.exit(fail>0?1:0);
